export function getMessageById(messageId: string) {
  return demoMessages.find((message) => message.id === messageId);
}

export function getLocalizedMessage(message: CustomerMessage, locale: Locale): CustomerMessage {
  const localized = message.localized?.[locale];
  return localized ? { ...message, ...localized } : message;
}

export function getProfileByMessageId(messageId: string) {
  return customerProfiles.find((profile) => profile.messageId === messageId);
}

export function getLocalizedProfile(profile: CustomerProfile, locale: Locale): CustomerProfile {
  const localized = profile.localized?.[locale];
  return localized ? { ...profile, ...localized } : profile;
}

export function getLocalizedProfiles(locale: Locale) {
  return customerProfiles.map((profile) => getLocalizedProfile(profile, locale));
}

export function getLocalizedMessages(locale: Locale) {
  return demoMessages.map((message) => getLocalizedMessage(message, locale));
}

export function getLocalizedProperty(property: Property, locale: Locale): Property {
  if (locale !== "tr") return property;
  return {
    ...property,
    title: property.titleTr ?? property.title,
    location: property.locationTr ?? property.location,
    parking: property.parkingTr ?? property.parking,
    description: property.descriptionTr ?? property.description,
    features: property.featuresTr ?? property.features,
  };
}

export function getLocalizedProperties(locale: Locale) {
  return demoProperties.map((property) => getLocalizedProperty(property, locale));
}
